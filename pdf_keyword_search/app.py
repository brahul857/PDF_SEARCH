def save_uploaded_pdf(uploaded_file) -> Path:
    """Save an upload once per file content using an autogenerated UUID filename."""
    content = uploaded_file.getvalue()
    content_hash = hashlib.sha256(content).hexdigest()

    if (
        st.session_state.get("uploaded_content_hash") == content_hash
        and st.session_state.get("saved_pdf_path")
    ):
        saved_path = Path(st.session_state["saved_pdf_path"])
        if saved_path.is_file():
            return saved_path

    generated_id = uuid.uuid4().hex
    saved_path = FILES_DIR / f"{generated_id}.pdf"
    saved_path.write_bytes(content)

    st.session_state["uploaded_content_hash"] = content_hash
    st.session_state["saved_pdf_path"] = str(saved_path)
    return saved_path


